import { closePool } from '../db/pool.js';
import { closeDb, getDb } from '../db/client.js';
import { runMigrations } from '../db/migrate.js';
import { dbBoolean } from '../db/sql-helpers.js';
import { checkPasswordPolicy } from '../auth/password-policy.js';
import { recordAudit } from '../audit/audit.service.js';
import { createLocalUser, normalizeEmail, setOneTimePassword } from '../admin/local-accounts.service.js';

/**
 * canvas-ez1.3: the first admin of an AUTH_MODE=local environment, which has no seeded accounts
 * (the dev seed's published passwords must never exist there). Run by the canvas-bootstrap-admin
 * Container Apps job (infra/azure/modules/bootstrapadminjob.bicep), which deploy.sh starts after
 * migrations; the password is generated by deploy.sh into infra/azure/.secrets/ and reaches this
 * script through Key Vault. Never logs the password.
 *
 * BOOTSTRAP_MODE=create (default): creates BOOTSTRAP_ADMIN_EMAIL as an admin whose password is a
 *   one-time password (changed at first sign-in) -- unless that account already exists, in which
 *   case nothing changes, so every deploy can run it without undoing the admin's own password.
 * BOOTSTRAP_MODE=reset: recovery for a lone admin who can't sign in (infra/azure/reset-admin.sh):
 *   makes the account an active admin again with BOOTSTRAP_ADMIN_PASSWORD as a new one-time
 *   password, and signs it out everywhere.
 *
 * Usage: BOOTSTRAP_ADMIN_EMAIL=... BOOTSTRAP_ADMIN_PASSWORD=... [BOOTSTRAP_ADMIN_NAME=...]
 *        [BOOTSTRAP_MODE=create|reset] npm run bootstrap-admin --workspace=@canvas/api
 */
export async function bootstrapAdmin(env: NodeJS.ProcessEnv): Promise<string> {
  const mode = env.BOOTSTRAP_MODE ?? 'create';
  if (mode !== 'create' && mode !== 'reset') throw new Error(`BOOTSTRAP_MODE must be create or reset (got: ${mode})`);
  if (!env.BOOTSTRAP_ADMIN_EMAIL) throw new Error('BOOTSTRAP_ADMIN_EMAIL is required.');
  const password = env.BOOTSTRAP_ADMIN_PASSWORD ?? '';
  const email = normalizeEmail(env.BOOTSTRAP_ADMIN_EMAIL);
  const problem = checkPasswordPolicy(password, { email });
  if (problem) throw new Error(`BOOTSTRAP_ADMIN_PASSWORD doesn't meet the password policy: ${problem}`);

  await runMigrations();
  const db = getDb();
  const existing = await db.selectFrom('users').select('id').where('email', '=', email).executeTakeFirst();

  if (mode === 'reset') {
    if (!existing) throw new Error(`No account with the email ${email} -- nothing to reset.`);
    await db.updateTable('users').set({ role: 'admin', active: dbBoolean(true) }).where('id', '=', existing.id).execute();
    await setOneTimePassword(existing.id, password);
    await recordAudit({ event: 'password_reset', targetUserId: existing.id, detail: { via: 'bootstrap-admin', unlocked: true } });
    return `bootstrap-admin: ${email} is an active admin again with a new one-time password; signed out everywhere.`;
  }

  if (existing) return `bootstrap-admin: ${email} already exists -- left unchanged.`;
  const { user } = await createLocalUser({ email, name: env.BOOTSTRAP_ADMIN_NAME ?? 'Administrator', role: 'admin' }, password);
  await recordAudit({ event: 'user_created', targetUserId: user.id, detail: { role: 'admin', via: 'bootstrap-admin' } });
  return `bootstrap-admin: created admin ${email}; the one-time password must be changed at first sign-in.`;
}

// Run as a script (not when imported by tests).
if (process.argv[1]?.endsWith('bootstrap-admin.js') || process.argv[1]?.endsWith('bootstrap-admin.ts')) {
  bootstrapAdmin(process.env)
    .then((message) => console.log(message))
    .then(() => Promise.all([closeDb(), closePool()]))
    .catch((error: unknown) => {
      console.error(error instanceof Error ? error.message : error);
      process.exitCode = 1;
      return Promise.all([closeDb(), closePool()]);
    });
}
