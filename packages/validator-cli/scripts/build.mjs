// canvas-3s5.3: bundles the validator into one dependency-free file, dist/validator.mjs, which
// Canvas commits to a repository as .canvas/validator.mjs on every submission (identical content
// leaves the repository unchanged). Also copies the example workflow next to it, where the API
// serves both from.
import { copyFileSync, mkdirSync, readFileSync, statSync } from 'node:fs';
import { build } from 'esbuild';

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
mkdirSync('dist', { recursive: true });

await build({
  entryPoints: ['src/main.ts'],
  outfile: 'dist/validator.mjs',
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: true,
  legalComments: 'none',
  define: { __VALIDATOR_VERSION__: JSON.stringify(pkg.version) },
  banner: {
    js: [
      `// Canvas diagram validator ${pkg.version} -- generated by Canvas; do not edit.`,
      '// Run: node .canvas/validator.mjs --help',
      // yaml's CommonJS build calls require(); give the ES module bundle one.
      "import { createRequire as __canvasCreateRequire } from 'node:module'; const require = __canvasCreateRequire(import.meta.url);",
    ].join('\n'),
  },
  logLevel: 'warning',
});
copyFileSync('examples/canvas-diagrams.yml', 'dist/canvas-diagrams.yml');
// The bundle's size only.
// bearer:disable javascript_lang_logger_leak
console.log(`dist/validator.mjs ${(statSync('dist/validator.mjs').size / 1024).toFixed(0)} KB`);
